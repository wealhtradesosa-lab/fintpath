// 2. INGRESOS
// ═══════════════════════════════════════════════════════════════════════════
export async function exportIngresosPDF(ingresos, owners, trm, en = false) {
  const t = en ? L.en : L.es; LOC = t.loc; TAGLINE = t.tagline;
  const items = (ingresos || []).filter((i) => i.sim !== false);
  if (items.length === 0) {
    alert(t.sinItems(en ? "income items" : "ingresos"));
    return;
  }

  const mens = (i) => aCOP(i.mensual, i, trm);
  const totalMes = items.reduce((s, i) => s + mens(i), 0);

  await build(buildFilename(t.ingresos), (doc, autoTable) => {
    let y = chrome(doc, { titulo: t.ingresos });

    y = resumen(doc, y, [
      { label: t.fuentes, value: String(items.length) },
      { label: t.totalMensual, value: fm(totalMes), color: [22, 163, 74] },
      { label: t.totalAnual, value: fm(totalMes * 12), color: [22, 163, 74] },
    ]);

    autoTable(doc, {
      ...tableStyle,
      startY: y,
      head: [[t.fuente, t.categoria, t.propTipo, t.propietario, t.mensual, t.anual]],
      body: items
        .slice()
        .sort((a, b) => mens(b) - mens(a))
        .map((i) => [
          i.nombre || "",
          i.categoria || "",
          i.tipo || "fijo",
          ownerName(i.ownerId, owners),
          fm(mens(i)),
          fm(mens(i) * 12),
        ]),
      foot: [[t.total, "", "", "", fm(totalMes), fm(totalMes * 12)]],
      columnStyles: { 4: { halign: "right" }, 5: { halign: "right" } },
    });

    const porCat = {};
    items.forEach((i) => {
      const cat = i.categoria || "Sin categoría";
      if (!porCat[cat]) porCat[cat] = { count: 0, mensual: 0 };
      porCat[cat].count += 1;
      porCat[cat].mensual += mens(i);
    });

    autoTable(doc, {
      ...tableStyle,
      startY: doc.lastAutoTable.finalY + 10,
      head: [[t.categoria, t.nIngresos, t.mensual, t.anual, t.pctTotal]],
      body: Object.entries(porCat)
        .sort((a, b) => b[1].mensual - a[1].mensual)
        .map(([cat, d]) => [
          cat,
          String(d.count),
          fm(d.mensual),
          fm(d.mensual * 12),
          totalMes > 0 ? pct((d.mensual / totalMes) * 100) : "0.0%",
        ]),
      columnStyles: {
        1: { halign: "right" }, 2: { halign: "right" },
        3: { halign: "right" }, 4: { halign: "right" },
      },
    });
  }, t.nota);
}

