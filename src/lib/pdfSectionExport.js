// 1. PATRIMONIO
// ═══════════════════════════════════════════════════════════════════════════
export async function exportPatrimonioPDF(inversiones, owners, trm, en = false) {
  const t = en ? L.en : L.es; LOC = t.loc; TAGLINE = t.tagline;
  const items = (inversiones || []).filter((i) => i.sim !== false);
  if (items.length === 0) {
    alert(t.sinItems(en ? "assets" : "activos"));
    return;
  }

  const totalVa = items.reduce((s, i) => s + aCOP(i.va, i, trm), 0);
  const totalVc = items.reduce((s, i) => s + aCOP(i.vc, i, trm), 0);
  const gain = totalVa - totalVc;
  const gainPct = totalVc > 0 ? ((totalVa / totalVc) - 1) * 100 : 0;

  await build(buildFilename(t.patrimonio), (doc, autoTable) => {
    let y = chrome(doc, { titulo: t.patrimonio });

    y = resumen(doc, y, [
      { label: t.activos, value: String(items.length) },
      { label: t.valorCompra, value: fm(totalVc) },
      { label: t.valorActual, value: fm(totalVa) },
      {
        label: t.ganancia,
        value: `${fm(gain)} (${gainPct >= 0 ? "+" : ""}${gainPct.toFixed(1)}%)`,
        color: gain >= 0 ? [22, 163, 74] : [220, 38, 38],
      },
    ]);

    autoTable(doc, {
      ...tableStyle,
      startY: y,
      head: [[t.activo, t.tipo, t.propietario, t.valorCompra, t.valorActual, t.ganancia, "%"]],
      body: items
        .slice()
        .sort((a, b) => aCOP(b.va, b, trm) - aCOP(a.va, a, trm))
        .map((i) => {
          const vc = aCOP(i.vc, i, trm);
          const va = aCOP(i.va, i, trm);
          const g = va - vc;
          return [
            i.nombre || i.n || "",
            i.tp || i.tipo || "Otro",
            ownerName(i.ownerId, owners),
            fm(vc),
            fm(va),
            fm(g),
            vc > 0 ? `${g >= 0 ? "+" : ""}${(((va / vc) - 1) * 100).toFixed(1)}%` : "—",
          ];
        }),
      foot: [[t.total, "", "", fm(totalVc), fm(totalVa), fm(gain), `${gainPct >= 0 ? "+" : ""}${gainPct.toFixed(1)}%`]],
      columnStyles: {
        3: { halign: "right" }, 4: { halign: "right" },
        5: { halign: "right" }, 6: { halign: "right" },
      },
    });

    // Desglose por tipo: responde "en qué está concentrado mi patrimonio",
    // que es la pregunta real detrás de exportar esta sección.
    const porTipo = {};
    items.forEach((i) => {
      const tp = i.tp || i.tipo || "Otro";
      if (!porTipo[tp]) porTipo[tp] = { count: 0, va: 0 };
      porTipo[tp].count += 1;
      porTipo[tp].va += aCOP(i.va, i, trm);
    });

    autoTable(doc, {
      ...tableStyle,
      startY: doc.lastAutoTable.finalY + 10,
      head: [[t.concentracion, t.nActivos, t.valorActual, t.pctPortafolio]],
      body: Object.entries(porTipo)
        .sort((a, b) => b[1].va - a[1].va)
        .map(([tp, d]) => [
          tp,
          String(d.count),
          fm(d.va),
          totalVa > 0 ? pct((d.va / totalVa) * 100) : "0.0%",
        ]),
      columnStyles: { 1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" } },
    });
  }, t.nota);
}

