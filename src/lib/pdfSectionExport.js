// 3. GASTOS
// ═══════════════════════════════════════════════════════════════════════════
export async function exportGastosPDF(gastos, trm, en = false) {
  const t = en ? L.en : L.es; LOC = t.loc; TAGLINE = t.tagline;
  // gastos llega como objeto { categoria: [items] }, igual que en Excel.
  const flat = [];
  Object.entries(gastos || {}).forEach(([cat, items]) => {
    (items || [])
      .filter((g) => g.sim !== false)
      .forEach((g) => {
        flat.push({
          categoria: cat,
          concepto: g.c || "",
          monto: aCOP(g.m, g, trm),
          tipo: g.t === "f" ? t.fijo : t.variable,
        });
      });
  });

  if (flat.length === 0) {
    alert(t.sinItems(en ? "expenses" : "gastos"));
    return;
  }

  const totalMes = flat.reduce((s, g) => s + g.monto, 0);
  const fijos = flat.filter((g) => g.tipo === t.fijo).reduce((s, g) => s + g.monto, 0);
  const variables = totalMes - fijos;

  await build(buildFilename(t.gastos), (doc, autoTable) => {
    let y = chrome(doc, { titulo: t.gastos });

    // Fijos vs variables va arriba a propósito: es el dato que decide cuánto
    // de tu gasto podés mover si necesitás ajustar.
    y = resumen(doc, y, [
      { label: t.items, value: String(flat.length) },
      { label: t.totalMensual, value: fm(totalMes), color: [220, 38, 38] },
      { label: t.fijos, value: `${fm(fijos)} (${totalMes > 0 ? pct((fijos / totalMes) * 100) : "0.0%"})` },
      { label: t.variables, value: `${fm(variables)} (${totalMes > 0 ? pct((variables / totalMes) * 100) : "0.0%"})` },
    ]);

    autoTable(doc, {
      ...tableStyle,
      startY: y,
      head: [[t.categoria, t.concepto, t.propTipo, t.mensual, t.anual]],
      body: flat
        .slice()
        .sort((a, b) => b.monto - a.monto)
        .map((g) => [g.categoria, g.concepto, g.tipo, fm(g.monto), fm(g.monto * 12)]),
      foot: [[t.total, "", "", fm(totalMes), fm(totalMes * 12)]],
      columnStyles: { 3: { halign: "right" }, 4: { halign: "right" } },
    });

    const porCat = {};
    flat.forEach((g) => {
      if (!porCat[g.categoria]) porCat[g.categoria] = { count: 0, fijos: 0, variables: 0 };
      porCat[g.categoria].count += 1;
      if (g.tipo === t.fijo) porCat[g.categoria].fijos += g.monto;
      else porCat[g.categoria].variables += g.monto;
    });

    autoTable(doc, {
      ...tableStyle,
      startY: doc.lastAutoTable.finalY + 10,
      head: [[t.categoria, t.nItems, t.fijos, t.variables, t.mensual, t.pctTotal]],
      body: Object.entries(porCat)
        .map(([cat, d]) => ({ cat, ...d, total: d.fijos + d.variables }))
        .sort((a, b) => b.total - a.total)
        .map((d) => [
          d.cat,
          String(d.count),
          fm(d.fijos),
          fm(d.variables),
          fm(d.total),
          totalMes > 0 ? pct((d.total / totalMes) * 100) : "0.0%",
        ]),
      columnStyles: {
        1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" },
        4: { halign: "right" }, 5: { halign: "right" },
      },
    });
  }, t.nota);
}

