// 4. DEUDAS
// ═══════════════════════════════════════════════════════════════════════════
export async function exportDeudasPDF(deudas, inversiones, owners, trm, en = false) {
  const t = en ? L.en : L.es; LOC = t.loc; TAGLINE = t.tagline;
  // Mismo filtro que el Excel: además de sim !== false, exige saldo > 0.
  // Una deuda saldada no es una deuda.
  const items = (deudas || []).filter((d) => d.sim !== false && (d.mt || 0) > 0);
  if (items.length === 0) {
    alert(t.sinItems(en ? "debts" : "deudas"));
    return;
  }

  const invName = (invId) => {
    if (!invId) return "";
    const inv = (inversiones || []).find((x) => x.id === invId);
    return inv ? inv.nombre || inv.n || "" : "";
  };

  const saldo = (d) => aCOP(d.mt, d, trm);
  const cuota = (d) => aCOP(d.pg, d, trm);
  const totalSaldo = items.reduce((s, d) => s + saldo(d), 0);
  const totalCuota = items.reduce((s, d) => s + cuota(d), 0);
  // Tasa promedio ponderada por saldo: el promedio simple miente cuando hay
  // una tarjeta chica al 30% junto a una hipoteca grande al 12%.
  const tasaPond = totalSaldo > 0
    ? items.reduce((s, d) => s + (d.ts || 0) * saldo(d), 0) / totalSaldo
    : 0;

  await build(buildFilename(t.deudas), (doc, autoTable) => {
    let y = chrome(doc, { titulo: t.deudas });

    y = resumen(doc, y, [
      { label: t.deudas, value: String(items.length) },
      { label: t.saldoTotal, value: fm(totalSaldo), color: [220, 38, 38] },
      { label: t.cuotaMensual, value: fm(totalCuota) },
      { label: t.tasaProm, value: pct(tasaPond) },
    ]);

    autoTable(doc, {
      ...tableStyle,
      startY: y,
      head: [[t.deuda, t.propietario, t.vinculada, t.saldo, t.cuotaMes, t.tasa, t.meses]],
      body: items
        .slice()
        .sort((a, b) => saldo(b) - saldo(a))
        .map((d) => {
          const meses = d.meses || d.n_cuotas || 0;
          return [
            d.n || d.nombre || "",
            ownerName(d.ownerId, owners),
            invName(d.invId),
            fm(saldo(d)),
            fm(cuota(d)),
            pct(d.ts || 0),
            meses > 0 ? String(meses) : "—",
          ];
        }),
      foot: [[t.total, "", "", fm(totalSaldo), fm(totalCuota), pct(tasaPond), ""]],
      columnStyles: {
        3: { halign: "right" }, 4: { halign: "right" },
        5: { halign: "right" }, 6: { halign: "right" },
      },
    });

    // Orden por tasa: es el orden en que conviene pagarlas (método avalancha).
    // La tabla de arriba va por saldo, que es lo que pesa; esta va por costo,
    // que es lo que decide cuál atacar primero.
    autoTable(doc, {
      ...tableStyle,
      startY: doc.lastAutoTable.finalY + 10,
      head: [[t.ordenPago, t.tasa, t.saldo, t.costoIntereses]],
      body: items
        .slice()
        .sort((a, b) => (b.ts || 0) - (a.ts || 0))
        .map((d) => [
          d.n || d.nombre || "",
          pct(d.ts || 0),
          fm(saldo(d)),
          fm(((d.ts || 0) / 100) * saldo(d)),
        ]),
      columnStyles: { 1: { halign: "right" }, 2: { halign: "right" }, 3: { halign: "right" } },
    });
  }, t.nota);
}
